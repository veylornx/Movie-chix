/* ---------- 1. Movie data ----------
   Every film lives on the Internet Archive, so one identifier
   (the last part of archive.org/details/<identifier>) is enough
   to build the poster, watch, embed and download URLs.

   TO ADD A FILM: open its page on archive.org, copy the
   identifier from the address bar, and add one line below.
   Always confirm the item's "Rights" / "Usage" field says
   Public Domain or a license that permits free sharing. */

const ARCHIVE = "https://archive.org";

function film(archiveId, title, year, director, description) {
  return {
    archiveId,
    title,
    year,
    director,
    description,
    poster: `${ARCHIVE}/services/img/${archiveId}`,   // thumbnail generated by the Archive
    watchUrl: `${ARCHIVE}/details/${archiveId}`,       // item page
    embedUrl: `${ARCHIVE}/embed/${archiveId}`,         // embeddable player
    downloadUrl: `${ARCHIVE}/download/${archiveId}`    // lists every downloadable file
  };
}

