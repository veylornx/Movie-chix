/* ---------- 2. Rendering ---------- */

const grid = document.getElementById("movie-grid");
const emptyState = document.getElementById("empty-state");
const resultCount = document.getElementById("result-count");
const searchInput = document.getElementById("search");

/* Build one card. Elements are created with the DOM API (not innerHTML)
   so data can never inject markup into the page. */
function createCard(movie) {
  const card = document.createElement("article");
  card.className = "card";

  // Poster (button that opens the player)
  const posterBtn = document.createElement("button");
  posterBtn.type = "button";
  posterBtn.className = "poster-btn";
  posterBtn.setAttribute("aria-label", `Watch ${movie.title}`);
  posterBtn.addEventListener("click", () => openPlayer(movie));

  const img = document.createElement("img");
  img.src = movie.poster;
  img.alt = `Poster for ${movie.title}`;
  img.loading = "lazy";
  // If the image is missing, swap in a text placeholder
  img.addEventListener("error", () => {
    const fallback = document.createElement("div");
    fallback.className = "poster-fallback";
    fallback.textContent = movie.title;
    img.replaceWith(fallback);
  });
  posterBtn.appendChild(img);

  // Text details
  const body = document.createElement("div");
  body.className = "card-body";

  const title = document.createElement("h3");
  title.textContent = movie.title;

  const year = document.createElement("p");
  year.className = "year";
  year.textContent = movie.year;

  const director = document.createElement("p");
  director.className = "director";
  director.textContent = movie.director;

  const desc = document.createElement("p");
  desc.className = "desc";
  desc.textContent = movie.description;

  // Actions
  const actions = document.createElement("div");
  actions.className = "actions";

  const watchBtn = document.createElement("button");
  watchBtn.type = "button";
  watchBtn.className = "btn btn-primary";
  watchBtn.textContent = "Watch";
  watchBtn.setAttribute("aria-label", `Watch ${movie.title}`);
  watchBtn.addEventListener("click", () => openPlayer(movie));

  const downloadLink = document.createElement("a");
  downloadLink.className = "btn";
  downloadLink.href = movie.downloadUrl;
  downloadLink.target = "_blank";
  downloadLink.rel = "noopener";
  downloadLink.textContent = "Download";
  downloadLink.setAttribute("aria-label", `Download ${movie.title}`);

  actions.append(watchBtn, downloadLink);
  body.append(title, year, director, desc, actions);
  card.append(posterBtn, body);
  return card;
}

/* Replace the grid contents with the given list of movies */
function renderMovies(list) {
  grid.replaceChildren(...list.map(createCard));

  emptyState.hidden = list.length > 0;
  resultCount.textContent =
    list.length === 1 ? "1 film" : `${list.length} films`;
}

/* ---------- 3. Search filter ---------- */

/* Case-insensitive match against title, year, director and description */
function filterMovies(query) {
  const q = query.trim().toLowerCase();
  if (!q) return movies;

  return movies.filter((m) =>
    [m.title, String(m.year), m.director, m.description]
      .join(" ")
      .toLowerCase()
      .includes(q)
  );
}

searchInput.addEventListener("input", () => {
  renderMovies(filterMovies(searchInput.value));
});

/* ---------- 4. Player dialog ---------- */

const player = document.getElementById("player");
const playerFrame = document.getElementById("player-frame");
const playerTitle = document.getElementById("player-title");
const playerClose = document.getElementById("player-close");

function openPlayer(movie) {
  playerTitle.textContent = movie.title;
  playerFrame.src = movie.embedUrl;
  player.showModal();
}

// Clearing src stops playback when the dialog closes
player.addEventListener("close", () => {
  playerFrame.src = "about:blank";
});

playerClose.addEventListener("click", () => player.close());

// Clicking the dark backdrop (outside the dialog box) also closes it
player.addEventListener("click", (event) => {
  if (event.target === player) player.close();
});

/* ---------- Start ---------- */
document.getElementById("year").textContent = new Date().getFullYear();
renderMovies(movies);
